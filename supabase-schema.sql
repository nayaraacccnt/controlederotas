create or replace function public.current_organization_id()
returns uuid language sql stable security definer set search_path = public
as $$ select organization_id from public.profiles where id = auth.uid() $$;

create or replace function public.has_permission(required_permission text)
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.profiles p join public.roles r on r.id = p.role_id
    where p.id = auth.uid()
      and (r.permissions @> array['*']::text[] or r.permissions @> array[required_permission]::text[])
      and not (
        r.name in ('Central de Emergência', 'Despachante', 'Equipe de Campo')
        and required_permission in ('fleet.view', 'fleet.manage', 'routes.view', 'routes.manage', 'drivers.view', 'drivers.manage', 'incidents.view', 'incidents.manage', 'dashboard.view', 'reports.view')
      )
  )
$$;

create or replace function public.can_access_route(target_route_id uuid)
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.routes r
    where r.id = target_route_id
      and r.organization_id = public.current_organization_id()
      and (
        (r.operation_area = 'eventos' and public.has_permission('routes.view'))
        or (r.operation_area = 'emergencia' and public.has_permission('emergency.view'))
        or (r.status in ('Publicada', 'Em andamento') and exists (
          select 1 from public.route_assignments a
          where a.route_id = r.id
            and a.driver_id = (select p.driver_id from public.profiles p where p.id = auth.uid())
        ))
      )
  )
$$;

create or replace function public.can_access_route_stop(target_route_id uuid, target_vehicle_id bigint)
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.routes visible_route where visible_route.id = target_route_id and visible_route.organization_id = public.current_organization_id() and ((visible_route.operation_area = 'eventos' and public.has_permission('routes.view')) or (visible_route.operation_area = 'emergencia' and public.has_permission('emergency.view')))) or exists (
    select 1 from public.routes r join public.route_assignments a on a.route_id = r.id
    where r.id = target_route_id
      and r.organization_id = public.current_organization_id()
      and r.status in ('Publicada', 'Em andamento')
      and a.driver_id = (select p.driver_id from public.profiles p where p.id = auth.uid())
      and (target_vehicle_id is null or target_vehicle_id = a.vehicle_id)
  )
$$;

